export function buildSchemaCatalogResponse(): unknown {
  const counts = { business: 0, api: 0, system: 0 };
  const schemas = schemaCatalogEntries.map((entry) => {
    counts[entry.category] += 1;
    return { ...entry, schemaId: entry.schema.$id };
  });
  return { schemas, counts, generatedAt: new Date().toISOString() };
}
