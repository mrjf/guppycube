export function describeValidationErrors(errors: ErrorObject[] | null | undefined): string {
  if (!errors?.length) return "Schema validation failed";
  return errors
    .map((error) => `${error.instancePath || "/"} ${error.message ?? "is invalid"}`)
    .join("; ");
}
