import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import {
  addComputerInputSchema,
  apiErrorSchema,
  clientSocketMessageSchema,
  createGameInputSchema,
  devProjectSchema,
  gameSessionSchema,
  healthResponseSchema,
  hubDiscoverySchema,
  joinGameInputSchema,
  okResponseSchema,
  playerLinkSchema,
  publicGameStateSchema,
  registrationResponseSchema,
  roomResultSchema,
  saveTurnDraftInputSchema,
  schemaCatalogResponseSchema,
  serverSocketMessageSchema,
  sessionCredentialsSchema,
  setAssistInputSchema,
  startGameInputSchema,
  storedGameSchema,
  takeActionInputSchema,
  turnActionSchema,
  unregisterResponseSchema,
} from "../src/schemas.ts";

const schemaByKey = {
  addComputerInput: addComputerInputSchema,
  apiError: apiErrorSchema,
  clientSocketMessage: clientSocketMessageSchema,
  createGameInput: createGameInputSchema,
  devProject: devProjectSchema,
  gameSession: gameSessionSchema,
  healthResponse: healthResponseSchema,
  hubDiscovery: hubDiscoverySchema,
  joinGameInput: joinGameInputSchema,
  okResponse: okResponseSchema,
  playerLink: playerLinkSchema,
  publicGameState: publicGameStateSchema,
  registrationResponse: registrationResponseSchema,
  roomResult: roomResultSchema,
  saveTurnDraftInput: saveTurnDraftInputSchema,
  schemaCatalogResponse: schemaCatalogResponseSchema,
  serverSocketMessage: serverSocketMessageSchema,
  sessionCredentials: sessionCredentialsSchema,
  setAssistInput: setAssistInputSchema,
  startGameInput: startGameInputSchema,
  storedGame: storedGameSchema,
  takeActionInput: takeActionInputSchema,
  turnAction: turnActionSchema,
  unregisterResponse: unregisterResponseSchema,
} as const;

const ajv = new Ajv2020({
  allErrors: true,
  code: { esm: true, source: true },
  coerceTypes: false,
  removeAdditional: false,
  strict: true,
  useDefaults: false,
});
addFormats(ajv);

for (const [key, schema] of Object.entries(schemaByKey)) ajv.addSchema(schema, key);

const exportsByName = Object.fromEntries(
  Object.keys(schemaByKey).map((key) => [`${key}Validator`, key]),
);
const generated = standaloneCode(ajv, exportsByName)
  .replaceAll('require("ajv/dist/runtime/equal").default', "equal")
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length")
  .replaceAll('require("ajv-formats/dist/formats").fullFormats', "fullFormats");
const source = `// @ts-nocheck
// Generated by scripts/generate-validators.ts. Do not edit directly.
import equalModule from "ajv/dist/runtime/equal.js";
import ucs2lengthModule from "ajv/dist/runtime/ucs2length.js";
import formatsModule from "ajv-formats/dist/formats.js";
const equal = typeof equalModule === "function" ? equalModule : equalModule.default;
const ucs2length = typeof ucs2lengthModule === "function" ? ucs2lengthModule : ucs2lengthModule.default;
const { fullFormats } = formatsModule;
${generated}`;
const outputPath = resolve(import.meta.dir, "../src/generated/validators.ts");
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(JSON.stringify({ event: "validators_generated", count: Object.keys(schemaByKey).length }));
